#!/usr/bin/env python3
"""Build applications/INDEX.md: every application sorted by fit_score, with status.

Reads the frontmatter of applications/*.md (company, role, applied, status, fit_score, source).
Usage: tools/jobs_table.py   (run from the repo root)
"""
import pathlib, re

import sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import paths  # noqa: E402  (where the data folder is)
root = paths.DATA
rows = []
for f in sorted((root / "applications").glob("*.md")):
    if f.name == "INDEX.md":
        continue
    m = re.match(r"^---\n(.*?)\n---", f.read_text(), re.S)
    if not m:
        continue
    fm = {}
    for line in m.group(1).splitlines():
        k, _, v = line.partition(":")
        fm[k.strip()] = re.sub(r"\s+#.*$", "", v).strip()
    score = fm.get("fit_score", "")
    rows.append((int(score) if score.isdigit() else -1, f.name, fm))

rows.sort(key=lambda r: (-r[0], r[1]))
out = ["# Applications", "", "Generated by `tools/jobs_table.py`. Sorted by fit score (blank = not scored).", "",
       "| Score | Company | Role | Status | Applied | File |", "|------:|---------|------|--------|---------|------|"]
for s, name, fm in rows:
    out.append(f"| {s if s >= 0 else ''} | {fm.get('company','')} | {fm.get('role','')} | {fm.get('status','')} | {fm.get('applied','')} | [{name}]({name}) |")
(root / "applications" / "INDEX.md").write_text("\n".join(out) + "\n")
print(f"wrote applications/INDEX.md ({len(rows)} applications)")
